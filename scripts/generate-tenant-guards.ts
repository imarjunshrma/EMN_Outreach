// Generates prisma/sql/002_tenant_guards.sql from the Prisma schema.
// For every relation between two workspace-scoped models, a trigger refuses rows whose referenced record
// belongs to a different workspace (and therefore possibly a different tenant). Run after schema changes:
//   node --import tsx scripts/generate-tenant-guards.ts
// tests/unit/tenant-guards.test.ts fails if the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

export function tenantRelations(schema: string) {
  const models = new Map<string, string>();
  for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) models.set(m[1], m[2]);
  const scoped = new Set([...models].filter(([, b]) => /^\s+workspaceId\s/m.test(b)).map(([n]) => n));
  const out: Array<{ table: string; fk: string; parent: string }> = [];
  for (const [name, body] of models) {
    if (!scoped.has(name)) continue;
    for (const r of body.matchAll(/^\s+\w+\s+(\w+)\??\s+@relation\((?:"\w+",\s*)?fields:\s*\[(\w+)\],\s*references:\s*\[id\]/gm)) {
      if (r[2] !== 'workspaceId' && scoped.has(r[1])) out.push({ table: name, fk: r[2], parent: r[1] });
    }
  }
  return out;
}

export function renderGuards(schema: string) {
  const rels = tenantRelations(schema);
  const byTable = new Map<string, Array<{ fk: string; parent: string }>>();
  for (const r of rels) byTable.set(r.table, [...(byTable.get(r.table) ?? []), r]);
  const lines = [
    '-- GENERATED by scripts/generate-tenant-guards.ts — do not edit by hand.',
    '-- Tenant integrity guards (idempotent; applied by `npm run db:migrate`).',
    '',
    '-- 1) A record may only reference records of the same workspace (and therefore the same tenant).',
    'CREATE OR REPLACE FUNCTION emn_same_workspace() RETURNS trigger AS $$',
    'DECLARE fk uuid; pws uuid; i int := 0;',
    'BEGIN',
    '  WHILE i < TG_NARGS LOOP',
    "    EXECUTE format('SELECT ($1).%I::uuid', TG_ARGV[i]) USING NEW INTO fk;",
    '    IF fk IS NOT NULL THEN',
    `      EXECUTE format('SELECT "workspaceId" FROM %I WHERE id = $1', TG_ARGV[i + 1]) USING fk INTO pws;`,
    '      IF pws IS NOT NULL AND pws <> NEW."workspaceId" THEN',
    "        RAISE EXCEPTION 'Cross-tenant reference refused: %.% points to a % in another workspace', TG_TABLE_NAME, TG_ARGV[i], TG_ARGV[i + 1] USING ERRCODE = '23514';",
    '      END IF;',
    '    END IF;',
    '    i := i + 2;',
    '  END LOOP;',
    '  RETURN NEW;',
    'END $$ LANGUAGE plpgsql;',
    '',
  ];
  for (const [table, fks] of [...byTable].sort(([a], [b]) => a.localeCompare(b))) {
    const args = fks.map((f) => `'${f.fk}', '${f.parent}'`).join(', ');
    lines.push(`DROP TRIGGER IF EXISTS emn_tenant_guard ON "${table}";`);
    lines.push(`CREATE TRIGGER emn_tenant_guard BEFORE INSERT OR UPDATE ON "${table}" FOR EACH ROW EXECUTE FUNCTION emn_same_workspace(${args});`);
  }
  lines.push(
    '',
    '-- 2) A workspace can never move to another tenant.',
    'CREATE OR REPLACE FUNCTION emn_workspace_org_immutable() RETURNS trigger AS $$',
    'BEGIN',
    '  IF NEW."organizationId" IS DISTINCT FROM OLD."organizationId" THEN',
    "    RAISE EXCEPTION 'A workspace cannot be moved to another organization' USING ERRCODE = '23514';",
    '  END IF;',
    '  RETURN NEW;',
    'END $$ LANGUAGE plpgsql;',
    'DROP TRIGGER IF EXISTS emn_workspace_org_immutable ON "Workspace";',
    'CREATE TRIGGER emn_workspace_org_immutable BEFORE UPDATE ON "Workspace" FOR EACH ROW EXECUTE FUNCTION emn_workspace_org_immutable();',
    '',
    '-- 3) Platform audit trail and tenant status history are append-only.',
    'CREATE OR REPLACE FUNCTION emn_append_only() RETURNS trigger AS $$',
    'BEGIN',
    "  IF TG_OP = 'DELETE' AND current_setting('emn.allow_audit_delete', true) = 'on' THEN RETURN OLD; END IF;",
    "  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;",
    'END $$ LANGUAGE plpgsql;',
    'DROP TRIGGER IF EXISTS emn_append_only ON "PlatformAuditEvent";',
    'CREATE TRIGGER emn_append_only BEFORE UPDATE OR DELETE ON "PlatformAuditEvent" FOR EACH ROW EXECUTE FUNCTION emn_append_only();',
    'DROP TRIGGER IF EXISTS emn_append_only ON "OrganizationStatusChange";',
    'CREATE TRIGGER emn_append_only BEFORE UPDATE ON "OrganizationStatusChange" FOR EACH ROW EXECUTE FUNCTION emn_append_only();',
    '',
  );
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const sql = renderGuards(readFileSync('prisma/schema.prisma', 'utf8'));
  writeFileSync('prisma/sql/002_tenant_guards.sql', sql);
  console.log(`wrote prisma/sql/002_tenant_guards.sql (${tenantRelations(readFileSync('prisma/schema.prisma', 'utf8')).length} guarded relations)`);
}
