// Generates docs/saas/API_TENANT_SECURITY_MATRIX.md (from the live route registry) and
// docs/saas/TENANT_DATA_OWNERSHIP_MATRIX.md (from prisma/schema.prisma + the tenant-guard SQL).
// Run: npm run saas:matrices. Re-run whenever routes or models change; tests check freshness of the guards file.
import { readFileSync, writeFileSync } from 'node:fs';
process.env.DATABASE_URL ??= 'postgresql://unused@127.0.0.1/unused';
const { routes } = await import('../backend/src/http/router.js');
await import('../backend/src/app.js');

type R = (typeof routes)[number] & { orgPermission?: string; platformPermission?: string; allowWhenInactive?: boolean };
const rs = routes as R[];
const AUTH: Record<string, string> = {
  public: 'Public (no session). Webhooks verify provider signatures; tokens are single-use hashes.',
  user: 'Signed-in user; acts only on the caller\'s own account or memberships.',
  workspace: 'Workspace member (session or that workspace\'s API key). Tenant = workspace → organization resolved server-side from membership.',
  org: 'Organization member (session only). Tenant = :organizationId, accepted only if the caller has an OrganizationMember row.',
  platform: 'Platform staff only (User.platformRole + permission). Everyone else gets 404.',
};
const lines: string[] = [];
lines.push('# API tenant security matrix', '', '> Generated by `npm run saas:matrices` from the route registry — do not edit by hand.', '');
lines.push(`${rs.length} operations. Counts by authentication mode:`, '');
const by = (a: string) => rs.filter((r) => r.auth === a);
lines.push('| Mode | Operations | How the tenant is determined |', '|---|---|---|');
for (const a of ['public', 'user', 'workspace', 'org', 'platform']) lines.push(`| \`${a}\` | ${by(a).length} | ${AUTH[a]} |`);
lines.push('', '## Cross-cutting rules', '',
  '- Ids in URLs are selectors only. `workspace` routes call `resolveMembership(workspaceId)`; a non-member gets **404** (`NOT_FOUND`), never 403, so existence is not revealed.',
  '- Every service function takes the resolved `workspaceId`/`organizationId` from the context (`c.workspaceId`, `c.organizationId`) — never from the body — and filters every query by it (`findFirst({ where: { id, workspaceId } })`).',
  '- Status gate: SUSPENDED/CANCELLED organizations are read-only; DELETION_PENDING/DELETED are closed, except routes marked *inactive-ok* (billing, export, usage, deletion cancel).',
  '- Support grants give VIEWER access to one organization, block all writes, and write a `support.read` platform audit event per request.',
  '- State-changing session requests require `X-CSRF-Token`; API keys are bound to one workspace and rejected on `user`, `org` and `platform` routes.',
  '- Rate limits: per-route (below) plus per-organization API-key limits (`rl:tenant:<org>:api:<minute>`) and monthly `api_calls` metering.', '');
for (const a of ['public', 'user', 'org', 'platform', 'workspace']) {
  lines.push(`## \`${a}\` routes`, '', '| Method | Path | Tag | Access | Rate limit | Inactive-ok |', '|---|---|---|---|---|---|');
  for (const r of by(a).sort((x, y) => x.path.localeCompare(y.path) || x.method.localeCompare(y.method))) {
    const access = a === 'workspace' ? (r.role ?? 'any member') : a === 'org' ? (r.orgPermission ?? 'view') : a === 'platform' ? (r.platformPermission ?? 'any staff') : '—';
    const rl = r.rateLimit ? `${r.rateLimit.limit}/${r.rateLimit.windowSec}s per ${r.rateLimit.key ?? 'ip'}` : 'global';
    lines.push(`| ${r.method.toUpperCase()} | \`/api/v1${r.path}\` | ${r.tag} | ${access} | ${rl} | ${r.allowWhenInactive ? 'yes' : ''} |`);
  }
  lines.push('');
}
lines.push('## Routes outside the registry', '',
  '| Path | Protection |', '|---|---|',
  '| `POST /api/v1/webhooks/billing/stripe` | Raw body, Stripe signature (t= / v1= HMAC-SHA256, 5-minute tolerance), event-id dedupe in `BillingEvent` |',
  '| `POST /api/v1/webhooks/billing/razorpay` | Raw body, HMAC-SHA256 of the body with the webhook secret, event-id dedupe |',
  '| `GET /api/v1/openapi.json`, `/healthz`, `/readyz` | Public, no tenant data |', '');
writeFileSync('docs/saas/API_TENANT_SECURITY_MATRIX.md', lines.join('\n'));

// ---------------------------------------------------------------- data ownership
const schema = readFileSync('prisma/schema.prisma', 'utf8');
const guards = readFileSync('prisma/sql/002_tenant_guards.sql', 'utf8');
const models = [...schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)].map((m) => ({ name: m[1], body: m[2] }));
const PLATFORM = new Set(['User', 'Session', 'AiModelPrice', 'Plan', 'BillingEvent', 'PlatformAuditEvent', 'PasswordResetToken', 'MfaChallenge', 'OAuthState']);
const out: string[] = ['# Tenant data ownership matrix', '', '> Generated by `npm run saas:matrices` from `prisma/schema.prisma` and `prisma/sql/002_tenant_guards.sql`.', '',
  'Ownership chain: **Organization → Workspace → record**. `Workspace.organizationId` is NOT NULL and immutable (trigger `emn_workspace_org_immutable`), so a record\'s organization is always derivable from its workspace.', '',
  '| Model | Owner column | Scope | Cross-workspace references refused by trigger |', '|---|---|---|---|'];
let ws = 0, org = 0, plat = 0;
for (const m of models) {
  const hasWs = /^\s+workspaceId\s+String\b(?!\?)/m.test(m.body);
  const optWs = /^\s+workspaceId\s+String\?/m.test(m.body);
  const hasOrg = /^\s+organizationId\s+String/m.test(m.body);
  const guard = guards.match(new RegExp(`ON "${m.name}" FOR EACH ROW EXECUTE FUNCTION emn_same_workspace\\(([^)]*)\\)`));
  const cols = guard ? guard[1].split(',').map((s) => s.trim().replace(/'/g, '')).filter((_, i) => i % 2 === 0).join(', ') : '';
  let scope: string; let owner: string;
  if (m.name === 'Organization') { scope = 'Tenant root'; owner = '`id`'; org++; }
  else if (m.name === 'Workspace') { scope = 'Tenant (organization)'; owner = '`organizationId` (immutable)'; org++; }
  else if (hasWs) { scope = 'Workspace'; owner = '`workspaceId`'; ws++; }
  else if (hasOrg) { scope = 'Organization'; owner = '`organizationId`'; org++; }
  else if (optWs) { scope = 'Workspace or platform'; owner = '`workspaceId?`'; ws++; }
  else if (PLATFORM.has(m.name)) { scope = 'Platform / user-owned'; owner = '—'; plat++; }
  else { scope = 'Via parent'; owner = '(parent relation)'; ws++; }
  out.push(`| ${m.name} | ${owner} | ${scope} | ${cols || ''} |`);
}
out.splice(5, 0, `${models.length} models: ${ws} workspace-scoped, ${org} organization-level, ${plat} platform or user-owned.`, '');
writeFileSync('docs/saas/TENANT_DATA_OWNERSHIP_MATRIX.md', out.join('\n') + '\n');
console.log(`wrote docs/saas/API_TENANT_SECURITY_MATRIX.md (${rs.length} ops) and TENANT_DATA_OWNERSHIP_MATRIX.md (${models.length} models)`);
process.exit(0);
